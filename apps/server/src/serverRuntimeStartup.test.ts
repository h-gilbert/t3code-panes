it.effect("automatic pull only updates enabled, behind, clean default-branch checkouts", () =>
  Effect.gen(function* () {
    const pulled: string[] = [];
    const git = {
      statusDetails: (cwd: string) =>
        Effect.succeed({
          isRepo: true,
          isDefaultBranch: cwd !== "/feature",
          hasUpstream: true,
          hasWorkingTreeChanges: cwd === "/dirty",
          aheadCount: cwd === "/ahead" ? 1 : 0,
          behindCount: cwd === "/current" ? 0 : 1,
        } as never),
      pullCurrentBranch: (cwd: string) =>
        Effect.sync(() => {
          pulled.push(cwd);
          return {
            status: "pulled" as const,
            refName: "main",
            upstreamRef: "origin/main",
          };
        }),
    } as unknown as GitVcsDriver.GitVcsDriver["Service"];
    const project = (workspaceRoot: string) =>
      ({ id: ProjectId.make(workspaceRoot), workspaceRoot }) as never;
    const overrides = (entries: Record<string, boolean>) => ({
      ...DEFAULT_SERVER_SETTINGS,
      projectSettingsOverrides: Object.fromEntries(
        Object.entries(entries).map(([root, defaultAutoPull]) => [
          ProjectId.make(root),
          { defaultAutoPull },
        ]),
      ),
    });

    yield* ServerRuntimeStartup.autoPullProjects(
      [
        project("/clean"),
        project("/current"),
        project("/dirty"),
        project("/ahead"),
        project("/feature"),
        project("/disabled"),
      ],
      overrides({
        "/clean": true,
        "/current": true,
        "/dirty": true,
        "/ahead": true,
        "/feature": true,
        "/disabled": false,
      }),
    ).pipe(Effect.provideService(GitVcsDriver.GitVcsDriver, git));

    assert.deepStrictEqual(pulled, ["/clean"]);

    pulled.length = 0;
    yield* ServerRuntimeStartup.autoPullProjects(
      [project("/inherited"), project("/opted-out"), project("/dirty")],
      { ...overrides({ "/opted-out": false }), defaultAutoPull: true },
    ).pipe(Effect.provideService(GitVcsDriver.GitVcsDriver, git));
    assert.deepStrictEqual(pulled, ["/inherited"]);
  }),
);

it.effect.each([
  {
    existing: false,
    machineModel: null,
    projectModel: null,
    machineMode: "full-access",
    projectMode: null,
  },
  {
    existing: false,
    machineModel: "claude-sonnet-4-6",
    projectModel: null,
    machineMode: "approval-required",
    projectMode: null,
  },
  {
    existing: true,
    machineModel: "claude-sonnet-4-6",
    projectModel: null,
    machineMode: "auto",
    projectMode: null,
  },
  {
    existing: true,
    machineModel: "claude-sonnet-4-6",
    projectModel: "gpt-5.4",
    machineMode: "full-access",
    projectMode: "auto-accept-edits",
  },
] as const)("auto-bootstrap model and permissions precedence: %j", (options) =>
  Effect.gen(function* () {
    const { machineModel, projectModel, machineMode, projectMode } = options;
    const projectId = ProjectId.make("startup-project");
    const machineSelection = machineModel
      ? { instanceId: ProviderInstanceId.make("claude-code"), model: machineModel }
      : null;
    const projectSelection = projectModel
      ? { instanceId: ProviderInstanceId.make("codex"), model: projectModel }
      : null;
    let createdProject: unknown;
    let launched: Parameters<ThreadLaunch.ThreadLaunchService["Service"]["launch"]>[0] | undefined;
    const targets = yield* ServerRuntimeStartup.resolveAutoBootstrapWelcomeTargets.pipe(
      Effect.provideService(ServerConfig.ServerConfig, {
        cwd: "/tmp/startup-project",
        autoBootstrapProjectFromCwd: true,
      } as never),
      Effect.provideService(ProjectService.ProjectService, {
        bootstrap: (input: unknown) => {
          createdProject = input;
          return Effect.succeed({ project: { id: projectId, defaultModelSelection: null } });
        },
      } as never),
      Effect.provideService(ThreadManagement.ThreadManagementService, {
        getShellSnapshot: () => Effect.succeed({ threads: [] }),
      } as never),
      Effect.provideService(ThreadLaunch.ThreadLaunchService, {
        launch: (input: NonNullable<typeof launched>) => {
          launched = input;
          return Effect.succeed({ threadId: ThreadId.make("startup-thread") });
        },
      } as never),
      Effect.provide([
        ServerSettings.layerTest({
          ...DEFAULT_SERVER_SETTINGS,
          defaultModelSelection: machineSelection,
          defaultRuntimeMode: machineMode,
          projectSettingsOverrides: {
            [projectId]: {
              ...(projectSelection ? { defaultModelSelection: projectSelection } : {}),
              ...(projectMode ? { defaultRuntimeMode: projectMode } : {}),
            },
          },
        }),
        NodeServices.layer,
        NodeCrypto.layer,
      ]),
    );
    assert.equal(targets.bootstrapThreadId, "startup-thread");
    assert.notProperty(createdProject, "defaultModelSelection");
    assert.equal(launched?.runtimeMode, projectMode ?? machineMode);
    assert.deepStrictEqual(
      launched?.modelSelection,
      projectSelection ??
        machineSelection ??
        ServerRuntimeStartup.getAutoBootstrapThreadModelSelection(),
    );
  }),
);

